// Bank manifest generator — run at build time (package.json "prebuild")
// and checked in at src/lib/bank-manifest.ts. Regenerates the EXACT
// per-bank counts, stored-trusted counts, and id->bank map from the
// bank JSON files, so lazy loading never relies on hand-maintained
// numbers: availability labels, ledger counts, and practice subject
// counts all read the manifest instead of loading bank chunks.
//
// Deterministic: same bank files -> byte-identical output. The test
// suite (scripts/test-lazy-banks.mjs) re-runs this script to a temp
// file and diffs it against the checked-in manifest, so a stale
// manifest fails loudly instead of silently corrupting counts.
//
// Only the 16 REGISTERED banks are included. drawing_pe.json is dead /
// unregistered and is deliberately excluded (same rule as banks.ts).
// Run: node scripts/generate-bank-manifest.mjs
import fs from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const BANKS_DIR = join(ROOT, "src/data/banks");

export const BANK_KEYS = [
  "arabic",
  "drawing",
  "english",
  "gk",
  "islamiyat",
  "it",
  "maths",
  "pakstudies",
  "pastpapers",
  "pastpapers_reworded",
  "pe",
  "pedagogy",
  "science",
  "socialstudies",
  "tajweed",
  "urdu",
];

function isTrustedStored(q) {
  return q.reviewStatus === "owner-reviewed" || q.reviewStatus === "approved";
}

export function generateManifest() {
  const counts = {};
  const trusted = {};
  const idBank = {};
  for (const key of BANK_KEYS) {
    const items = JSON.parse(fs.readFileSync(join(BANKS_DIR, `${key}.json`), "utf8"));
    counts[key] = items.length;
    trusted[key] = items.filter(isTrustedStored).length;
    for (const q of items) {
      if (typeof q.id !== "string" || q.id.length === 0) {
        throw new Error(`bank ${key}: item without a string id`);
      }
      if (idBank[q.id] !== undefined) {
        throw new Error(`duplicate question id ${q.id} in banks ${idBank[q.id]} and ${key}`);
      }
      idBank[q.id] = key;
    }
  }
  const header = `// GENERATED by scripts/generate-bank-manifest.mjs — DO NOT EDIT BY HAND.\n// Regenerated on every build (package.json "prebuild") from the bank\n// JSON files. Exact per-bank counts, stored-trusted counts (reviewStatus\n// owner-reviewed/approved, no local overrides), and the question-id ->\n// bank map used by findQuestionById so a single lookup loads one chunk.\n// drawing_pe.json is dead/unregistered and is NOT in this manifest.\n`;
  const body = [
    `export const BANK_COUNTS: Record<string, number> = ${JSON.stringify(counts, null, 2)};`,
    ``,
    `export const BANK_TRUSTED: Record<string, number> = ${JSON.stringify(trusted, null, 2)};`,
    ``,
    `export const ID_BANK: Record<string, string> = ${JSON.stringify(idBank, null, 2)};`,
    ``,
  ].join("\n");
  return header + body;
}

const outPath = process.argv[2] ?? join(ROOT, "src/lib/bank-manifest.ts");
fs.writeFileSync(outPath, generateManifest());
console.log(`bank manifest written: ${outPath}`);
